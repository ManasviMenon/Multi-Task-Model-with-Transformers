def P(p):
    """p-value in LaTeX: 3 decimals, or m x 10^e below 0.001."""
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    if p >= 0.001:
        return f"{p:.3f}"
    e = math.floor(math.log10(p))
    m = p / 10 ** e
    if round(m, 1) >= 10:
        m, e = m / 10, e + 1
    return f"${m:.1f}\\times10^{{{e}}}$"


def C(n, t):
    return f"{n}/{t} ({100 * n / t:.2f}\\%)"


def star(p, alpha=0.05):
    return "$^{\\ast}$" if p < alpha else ""


def table(label, caption, colspec, header, rows, wide=False, notes=None, sep=4):
    env = "table*" if wide else "table"
    out = [f"\\begin{{{env}}}[!t]", "\\centering", "\\small" if not wide else "\\footnotesize",
           f"\\caption{{{caption}}}", f"\\label{{{label}}}", f"\\setlength{{\\tabcolsep}}{{{sep}pt}}",
           f"\\begin{{tabular}}{{{colspec}}}", "\\hline", " & ".join(header) + " \\\\", "\\hline"]
    out += [" & ".join(r) + " \\\\" for r in rows]
    out += ["\\hline", "\\end{tabular}"]
    if notes:
        out += ["\\\\[2pt]", f"\\parbox{{{'0.95' if wide else '0.98'}\\linewidth}}{{\\footnotesize {notes}}}"]
    out += [f"\\end{{{env}}}", ""]
    print("\n".join(out))


