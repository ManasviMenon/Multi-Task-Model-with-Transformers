"""Emit every results-section table as LaTeX, straight from the results files.

Run from the repository root:
    python research_graphs/paper_tables_latex.py > research_graphs/paper_tables.tex

Each table is a complete table/table* environment with the \\label the manuscript already uses
(tab:data, tab:walkforward, ...), so \\ref numbering is unchanged. Three tables are new, written
for the reviewer's items: tab:christoffersen, tab:baselines and tab:returnquantile. Every coverage
is printed as N/T and computed from those integers. Rejections at 5% are marked with an asterisk.
Uses only \\hline (no booktabs), which is safe under IEEEtran.
"""
